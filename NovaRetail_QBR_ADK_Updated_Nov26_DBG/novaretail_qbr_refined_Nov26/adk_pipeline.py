"""Google ADK orchestration for NovaRetail QBR narrative generation."""

import asyncio
import json
import os
from typing import Any

from google.adk.agents import LlmAgent, SequentialAgent
from google.adk.runners import Runner
from google.adk.sessions import InMemorySessionService
from google.genai import types
from pydantic import BaseModel, Field

APP_NAME = "novaretail_qbr"
USER_ID = "qbr_generator"
MODEL = os.getenv("ADK_MODEL", "gemini-3.8-flash")


class QBRNarrative(BaseModel):
    """Structured, model-generated narrative consumed by the PowerPoint builder."""

    executive_summary: str = Field(description="Two-sentence executive summary grounded in supplied metrics.")
    performance_title: str
    performance_insights: list[str] = Field(min_length=4, max_length=4)
    customer_title: str
    customer_insights: list[str] = Field(min_length=4, max_length=4)
    risk_title: str
    risk_insights: list[str] = Field(min_length=4, max_length=4)
    recommendations: list[str] = Field(min_length=4, max_length=4)
    closing_statement: str


metric_analyst = LlmAgent(
    name="metric_analyst",
    model=MODEL,
    instruction=(
        "Act as a retail business analyst. Review only the JSON metrics supplied by the user. "
        "Identify material quarter-over-quarter and regional patterns, risks, and opportunities. "
        "Never invent a value, recalculate an absent metric, or use external facts. Return concise "
        "analysis notes with every numerical claim tied to the input."
    ),
    output_key="analysis_notes",
)

executive_editor = LlmAgent(
    name="executive_editor",
    model=MODEL,
    instruction=(
        "Transform {analysis_notes} into a board-ready quarterly business review narrative. "
        "Use the original metrics in session state as the sole source of truth. Produce concise, "
        "action-oriented wording and return only data matching the required schema."
    ),
    output_schema=QBRNarrative,
    output_key="qbr_narrative",
)

# A sequential workflow makes the agentic handoff explicit: analysis first, editing second.
root_agent = SequentialAgent(
    name="novaretail_qbr_pipeline",
    sub_agents=[metric_analyst, executive_editor],
    description="Analyzes validated retail metrics and authors a structured QBR narrative.",
)


async def _run_pipeline(metrics: dict[str, Any]) -> QBRNarrative:
    """Run the ADK multi-agent workflow and return validated narrative content.

    Args:
        metrics: Deterministically calculated metrics and source rows from the workbook.

    Returns:
        A Pydantic-validated ``QBRNarrative`` instance.

    Raises:
        RuntimeError: If the ADK workflow does not emit a final structured response.
        ValidationError: If the model response does not satisfy ``QBRNarrative``.
    """
    session_service = InMemorySessionService()
    session = await session_service.create_session(
        app_name=APP_NAME,
        user_id=USER_ID,
        # Store the exact source payload in session state for traceability across agents.
        state={"metrics": metrics},
    )
    runner = Runner(
        app_name=APP_NAME,
        agent=root_agent,
        session_service=session_service,
    )
    prompt = (
        "Create the NovaRetail QBR narrative from this validated metrics payload. "
        "Do not add unsupported claims:\n" + json.dumps(metrics, default=str)
    )
    message = types.Content(role="user", parts=[types.Part(text=prompt)])
    final_text = None

    # Consume ADK events until the sequential workflow produces its final response.
    async for event in runner.run_async(
        user_id=USER_ID,
        session_id=session.id,
        new_message=message,
    ):
        if event.is_final_response() and event.content and event.content.parts:
            final_text = event.content.parts[0].text

    if not final_text:
        raise RuntimeError("The ADK workflow completed without a final narrative response.")
    return QBRNarrative.model_validate_json(final_text)


def generate_qbr_narrative(metrics: dict[str, Any]) -> QBRNarrative:
    """Synchronously invoke the Google ADK workflow for deck generation.

    Args:
        metrics: Validated workbook data and deterministic KPI calculations.

    Returns:
        Structured narrative generated by Gemini through Google ADK.
    """
    if not (os.getenv("GOOGLE_API_KEY") or os.getenv("GOOGLE_GENAI_USE_VERTEXAI")):
        raise EnvironmentError(
            "Configure GOOGLE_API_KEY, or configure Vertex AI and set "
            "GOOGLE_GENAI_USE_VERTEXAI=TRUE, before generating the deck."
        )
    return asyncio.run(_run_pipeline(metrics))
